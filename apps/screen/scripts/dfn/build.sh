#!/usr/bin/env bash
# Builds the DeepFilterNet3 noise-suppression wasm from upstream libDF at a
# pinned commit, plus the model archive, into an output directory. The output
# is what goes up as the `screen-dfn/<version>` GitHub Release; the app never
# builds Rust itself (see fetch.mjs and ARCHITECTURE.md).
#
#   scripts/dfn/build.sh <out-dir>
#
# Needs: git, cargo, `rustup target add wasm32-unknown-unknown`, wasm-pack.
set -euo pipefail

UPSTREAM="https://github.com/Rikorose/DeepFilterNet.git"
COMMIT="d375b2d8309e0935d165700c91da9de862a99c31"
MODEL="DeepFilterNet3_onnx.tar.gz"

out="$(mkdir -p "${1:?usage: build.sh <out-dir>}" && cd "$1" && pwd)"
here="$(cd "$(dirname "$0")" && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

git clone --quiet "$UPSTREAM" "$work/src"
git -C "$work/src" checkout --quiet "$COMMIT"
cd "$work/src/libDF"

# The `wasm` feature embeds the default model into the binary; we ship the
# model as its own file instead, so drop it from the feature.
sed -i.bak 's/^  "default-model",$//' Cargo.toml
grep -A8 '^wasm = \[' Cargo.toml | grep -q default-model && { echo "patch failed" >&2; exit 1; }
# The pinned wasm-bindgen (0.2.87) cannot read what current rustc emits.
cargo update --quiet -p wasm-bindgen

RUSTFLAGS="-C target-feature=+simd128" \
  wasm-pack build --target web --release --no-typescript --no-pack \
  --out-dir "$work/pkg" --out-name df -- --no-default-features --features wasm

cp "$work/pkg/df_bg.wasm" "$out/df_bg.wasm"
# The page compiles the wasm itself (engine.ts); drop the glue's default fetch
# path so Vite does not look for a df_bg.wasm next to it.
{
  echo "// Generated by scripts/dfn/build.sh (wasm-bindgen) from libDF $COMMIT. Do not edit."
  sed "s#new URL('df_bg.wasm', import.meta.url)#undefined#" "$work/pkg/df.js"
} > "$here/../../app/features/rtc/denoise/df-glue.js"
cp "$work/src/models/$MODEL" "$out/$MODEL"
cp "$work/src/LICENSE-MIT" "$work/src/LICENSE-APACHE" "$out/"
(cd "$out" && shasum -a 256 df_bg.wasm "$MODEL" > SHA256SUMS)
{
  echo "upstream: $UPSTREAM"
  echo "commit: $COMMIT"
  echo "rustc: $(rustc --version)"
  echo "wasm-pack: $(wasm-pack --version)"
  echo "wasm-bindgen: $(grep -A1 '^name = "wasm-bindgen"$' "$work/src/Cargo.lock" | sed -n 's/^version = "\(.*\)"/\1/p')"
} > "$out/BUILD-INFO"
cat "$out/SHA256SUMS" "$out/BUILD-INFO"
